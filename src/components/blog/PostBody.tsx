// ---------------------------------------------------------------------------
// PostBody — renders Sanity Portable Text as the article body.
//
// Why a dedicated component?
//   - We own the serializer map (`components`), so headings can emit
//     stable anchor IDs used by the ToC.
//   - Inline images pass through Sanity's CDN URL builder for size +
//     format, with captions.
//   - Link marks distinguish internal (same-site) vs external for sensible
//     `target` + `rel` defaults, and for analytics hooks in #012.
//   - Typography treatment (prose-* classes) stays in one place instead of
//     being sprinkled across the post page template.
//
// Heading IDs are generated by the same `slugifyHeading` helper used by
// TableOfContents so anchors and ToC entries line up deterministically —
// the ToC walks the raw body blocks and runs the same slugify pass.
//
// Introduced in CHANGELOG #009.
// ---------------------------------------------------------------------------

"use client";

import Image from "next/image";
import Link from "next/link";
import { PortableText, type PortableTextComponents } from "@portabletext/react";
import type {
    PortableTextBlock,
    PortableTextMarkDefinition,
} from "@portabletext/types";

import { urlFor } from "@/lib/sanity/image";
import { slugifyHeading } from "@/lib/blog/slugify";
import type { PortableTextBlocks } from "@/lib/sanity/types";

// Narrow the loose PortableTextBlocks type into the shape @portabletext/types expects.
type PortableTextInput = readonly PortableTextBlock[];

interface PostBodyProps {
    readonly blocks: PortableTextBlocks;
}

/**
 * Extract plain text from the children of a block node. Portable Text
 * children are usually `{ _type: 'span', text: string }` but can also be
 * inline objects — we only pull text spans for the heading slug.
 */
function blockText(children: unknown): string {
    if (!Array.isArray(children)) return "";
    return children
        .map((c) => {
            if (typeof c === "string") return c;
            if (
                c &&
                typeof c === "object" &&
                "props" in c &&
                typeof (c as { props: { children?: unknown } }).props
                    .children === "string"
            ) {
                return (c as { props: { children: string } }).props.children;
            }
            return "";
        })
        .join("");
}

/**
 * Heading renderer factory. Emits an <hN id="slug"> so in-page anchor
 * links resolve. Cursor-target-friendly scroll margin is applied so the
 * sticky header doesn't eclipse the heading when you jump to it.
 */
function makeHeading(level: 2 | 3 | 4) {
    const Tag = `h${level}` as "h2" | "h3" | "h4";
    function HeadingRenderer({ children }: { children?: React.ReactNode }) {
        const text = blockText(children);
        const id = slugifyHeading(text);
        const size =
            level === 2
                ? "text-2xl sm:text-3xl font-bold"
                : level === 3
                  ? "text-xl sm:text-2xl font-bold"
                  : "text-lg sm:text-xl font-semibold";
        return (
            <Tag
                id={id}
                className={`${size} scroll-mt-28 mt-10 mb-4 tracking-tight text-theme-text`}
                style={{ fontFamily: "'Plus Jakarta Sans', sans-serif" }}
            >
                {children}
            </Tag>
        );
    }
    HeadingRenderer.displayName = `Heading${level}`;
    return HeadingRenderer;
}

const components: PortableTextComponents = {
    block: {
        h2: makeHeading(2),
        h3: makeHeading(3),
        h4: makeHeading(4),
        normal: ({ children }) => (
            <p className="my-5 text-base leading-[1.85] text-theme-text/85 sm:text-lg">
                {children}
            </p>
        ),
        blockquote: ({ children }) => (
            <blockquote className="my-8 border-l-4 border-theme-accent/70 bg-theme-card/60 px-6 py-4 text-base italic text-theme-text/80 sm:text-lg">
                {children}
            </blockquote>
        ),
    },

    list: {
        bullet: ({ children }) => (
            <ul className="my-5 list-disc space-y-2 pl-6 text-base leading-[1.8] text-theme-text/85 sm:text-lg">
                {children}
            </ul>
        ),
        number: ({ children }) => (
            <ol className="my-5 list-decimal space-y-2 pl-6 text-base leading-[1.8] text-theme-text/85 sm:text-lg">
                {children}
            </ol>
        ),
    },

    listItem: {
        bullet: ({ children }) => <li className="pl-1">{children}</li>,
        number: ({ children }) => <li className="pl-1">{children}</li>,
    },

    marks: {
        strong: ({ children }) => (
            <strong className="font-semibold text-theme-text">
                {children}
            </strong>
        ),
        em: ({ children }) => <em className="italic">{children}</em>,
        code: ({ children }) => (
            <code className="rounded bg-theme-card px-1.5 py-0.5 text-[0.92em] font-mono text-theme-accent">
                {children}
            </code>
        ),
        link: ({
            children,
            value,
        }: {
            children?: React.ReactNode;
            value?: PortableTextMarkDefinition & { href?: string };
        }) => {
            const href = value?.href ?? "#";
            const isExternal = /^https?:\/\//.test(href);
            if (isExternal) {
                return (
                    <a
                        href={href}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="text-theme-accent underline decoration-theme-accent/40 underline-offset-4 transition-colors hover:decoration-theme-accent"
                    >
                        {children}
                    </a>
                );
            }
            return (
                <Link
                    href={href}
                    className="text-theme-accent underline decoration-theme-accent/40 underline-offset-4 transition-colors hover:decoration-theme-accent"
                >
                    {children}
                </Link>
            );
        },
    },

    types: {
        image: ({
            value,
        }: {
            value: {
                asset?: { _ref?: string };
                alt?: string;
                caption?: string;
            };
        }) => {
            if (!value?.asset) return null;
            const src = urlFor(value).width(1400).fit("max").url();
            return (
                <figure className="my-8">
                    <div className="relative overflow-hidden rounded-xl border border-theme-border/60 bg-theme-bg2">
                        {/* eslint-disable-next-line @next/next/no-img-element */}
                        <Image
                            src={src}
                            alt={value.alt ?? ""}
                            width={1400}
                            height={900}
                            sizes="(max-width: 768px) 100vw, 700px"
                            className="h-auto w-full object-cover"
                        />
                    </div>
                    {value.caption ? (
                        <figcaption className="mt-3 text-center text-sm text-theme-text/60">
                            {value.caption}
                        </figcaption>
                    ) : null}
                </figure>
            );
        },
    },
};

export default function PostBody({ blocks }: PostBodyProps) {
    return (
        <div className="post-body">
            <PortableText
                value={blocks as unknown as PortableTextBlock[]}
                components={components}
            />
        </div>
    );
}
